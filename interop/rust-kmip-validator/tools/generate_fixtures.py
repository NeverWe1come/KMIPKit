#!/usr/bin/env python3
"""Generate public certificate/CSR fixtures from the pinned local test-server PKI.

OASIS KMIP 2.1 §2.1 Tables 2-3; no private key or credential is retained.
"""
import json
from pathlib import Path
import shutil
import ssl
import subprocess
import tempfile
ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / "interop/rust-kmip-validator/tests/fixtures"
OUTPUT.mkdir(exist_ok=True)
with tempfile.TemporaryDirectory() as directory:
    path = Path(directory)
    server = subprocess.Popen([str(ROOT / "target/debug/kmipkit-test-server"), "--listen", "127.0.0.1:0", "--data-dir", str(path / "data"), "--export-pki", str(path / "pki"), "--json"], stdout=subprocess.PIPE, text=True)
    try:
        ready = json.loads(server.stdout.readline())
        assert ready["status"] == "running"
        cert = ssl.PEM_cert_to_DER_cert((path / "pki/client.crt").read_text())
        (OUTPUT / "certificate.der").write_bytes(cert)
        subprocess.run(["openssl", "req", "-new", "-sha256", "-key", str(path / "pki/client.key"), "-subj", "/CN=KMIPKit dedicated interop fixture", "-outform", "DER", "-out", str(OUTPUT / "certificate-request.der")], check=True)
    finally:
        server.terminate()
        server.wait(timeout=10)
(OUTPUT / "README.md").write_text("# Public local-server fixtures\n\nGenerated by tools/generate_fixtures.py using kmipkit-test-server from release\ncommit fdafef8a3eb0c7b4b18d6433b78fde4151493ceb.\nCertificate and PKCS#10 CSR are public test data for OASIS KMIP 2.1 §2.1\nTables 2–3. The ephemeral signing key is discarded and never committed.\n")
