#!/usr/bin/env python3
"""Generate direct installed Rust model calls; metadata is not execution evidence."""
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[3]
INSTALLED = ROOT / 'interop/.local/rust-live/install/crates/kmipkit-protocol-1.0.0/src'
ROUTES = json.loads((ROOT / 'interop/shared/coverage/route-capabilities.json').read_text())
source = (INSTALLED / 'typed_attributes_generated.rs').read_text()
markers = re.findall(r'marker_name: "([^"]+)",\s*tag: (0x[\da-fA-F_]+),\s*value_kind: "([^"]+)"', source)
OWNED = {
    'Boolean': ('Boolean', '*value'), 'ByteString': ('ByteString', 'value.to_vec()'),
    'DateTime': ('DateTime', '*value'), 'Enumeration': ('Enumeration', '*value'),
    'Integer': ('Integer', '*value'), 'Interval': ('Interval', '*value'),
    'TextString': ('TextString', 'value.to_owned()'),
}
lines = ['// Generated by tools/generate_route_calls.py; do not edit.',
         'use crate::models::Result;', 'use kmipkit::protocol::{attribute::{Attribute, typed}, AttributeSet, CurrentAttribute, NewAttribute};',
         'use kmipkit::ttlv::{Item, ValueView};',
         '#[allow(clippy::too_many_lines)] // One explicit public call per installed typed attribute route.',
         'pub(crate) fn execute(symbol: &str, sample: &Item) -> Option<Result<Item>> {',
         '    match symbol {']
for marker, tag, kind in markers:
    owner = f'kmipkit_protocol::attribute::Attribute::<kmipkit_protocol::attribute::typed::{marker}>'
    typed = f'Attribute::<typed::{marker}>'
    if kind == 'Structure':
        value = 'sample.as_structure().ok_or("attribute value mismatch")?.try_clone().map_err(|_| "attribute copy failed")?'
    elif kind == 'UniqueIdentifier':
        value = 'sample.with_value(|value| match value { ValueView::TextString(value) => Ok(kmipkit::protocol::attribute::UniqueIdentifierValue::TextString(value.to_owned())), ValueView::Integer(value) => Ok(kmipkit::protocol::attribute::UniqueIdentifierValue::Integer(*value)), ValueView::Enumeration(value) => Ok(kmipkit::protocol::attribute::UniqueIdentifierValue::Enumeration(*value)), _ => Err("attribute value mismatch") })?'
    else:
        variant, projection = OWNED[kind]
        value = f'sample.with_value(|value| match value {{ ValueView::{variant}(value) => Ok({projection}), _ => Err("attribute value mismatch") }})?'
    lines += [f'"{owner}::new" => {typed}::new({value}).map({typed}::into_item).map_err(|_| "typed constructor rejected"),',
              f'"{owner}::from_item" => {typed}::from_item(sample.try_clone().map_err(|_| "attribute copy failed")?).map({typed}::into_item).map_err(|_| "typed constructor rejected"),']
    for wrapper in ('CurrentAttribute', 'NewAttribute'):
        symbol = f'kmipkit_protocol::{wrapper}::from_typed::<kmipkit_protocol::attribute::typed::{marker}>'
        lines.append(f'"{symbol}" => {{ let attribute = {typed}::from_item(sample.try_clone().map_err(|_| "attribute copy failed")?).map_err(|_| "typed constructor rejected")?; {wrapper}::from_typed::<typed::{marker}>(attribute).item().try_clone().map_err(|_| "attribute copy failed") }},')
    symbol = f'kmipkit_protocol::AttributeSet::try_push_typed::<kmipkit_protocol::attribute::typed::{marker}>'
    lines.append(f'"{symbol}" => {{ let attribute = {typed}::from_item(sample.try_clone().map_err(|_| "attribute copy failed")?).map_err(|_| "typed constructor rejected")?; let mut set = AttributeSet::new(); set.try_push_typed::<typed::{marker}>(attribute).map_err(|_| "typed insertion rejected")?; set.as_items().first().ok_or("inserted attribute missing")?.try_clone().map_err(|_| "attribute copy failed") }},')
lines = [re.sub(r'^(' + chr(34) + r'.+?' + chr(34) + r') => (.*),$', r'\1 => Some((|| { \2 })()),', line) for line in lines]
lines += ['_ => None,', '}', '}']
output = ROOT / 'interop/rust-kmip-validator/src/route_calls_generated.rs'
output.write_text('\n'.join(lines) + '\n')
subprocess.run(['rustfmt', '+1.94', '--edition', '2024', str(output)], check=True)
