#!/usr/bin/env python3
"""Generate consumer local-model dispatch from reviewed normative inputs."""
import json
from pathlib import Path
import re
import sys
ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools/normative_catalog"))
from generate_named_values import _snake_identifier

elements = json.loads((ROOT / "specification/catalog/kmip-2.1.json").read_text())["elements"]
catalog = json.loads((ROOT / "interop/shared/catalog/kmipkit-1.0-test-catalog.json").read_text())
lines = ["// Generated by tools/generate_local_cases.py; do not edit.",
         "use kmipkit::protocol::named_values_generated::values::{enumeration, bitmask};",
         "pub(crate) fn verify(name: &str) -> bool {", "    match name {"]
for case in catalog["test_cases"]:
    if case["execution"]["mode"] != "local_model":
        continue
    req = case["requires"]
    kind, name = ("enumeration", req["enum_type"]) if "enum_type" in req else ("bitmask", req["bitmask_type"])
    group = next(e for e in elements if e["kind"] == kind and e["name"] == name)
    values = [e for e in elements if group["element_id"] in e["parent_element_ids"] and "wire_value" in e and re.fullmatch(r"(?:0x)?[0-9a-fA-F]{1,8}", e["wire_value"])]
    module = _snake_identifier(name)
    if kind == "enumeration":
        expressions = [f'enumeration::{module}::name(0x{int(e["wire_value"], 16):08x}).is_some()' for e in values]
    else:
        expressions = [f'bitmask::{module}::names(bitmask::{module}::KNOWN_MASK).count() == {len(values)}']
    expressions.append('super::generic_model_check()')
    lines.append(f'        "{case["case_id"]}" => ' + " && ".join(expressions) + ",")
lines.extend(["        _ => false,", "    }", "}", "", "pub(crate) fn attribute_tag(name: &str) -> Option<u32> {", "    match name {"])
for e in elements:
    if e["kind"] == "attribute":
        tags = [p for p in e["parent_element_ids"] if p.startswith("KMIPKIT-ELEM-TAG-")]
        if tags:
            lines.append(f'        "{e["name"]}" => Some(0x{tags[0].split("-")[-1]}),')
lines.extend(["        _ => None,", "    }", "}", ""])
output = ROOT / "interop/rust-kmip-validator/src/local_cases_generated.rs"
output.write_text("\n".join(lines))
