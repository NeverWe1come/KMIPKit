def _language_declarations(projection: dict[str, Any], language: str) -> list[dict[str, str]]:
    package_ids = {
        package["id"]
        for package in projection["publicPackages"]
        if package["language"] == language
    }
    return [
        {
            "declarationId": declaration["declarationId"],
            "packageId": declaration["packageId"],
            "kind": declaration["kind"],
            "name": declaration["languageMappings"][language]["name"],
        }
        for declaration in projection["publicDeclarations"]
        if declaration["packageId"] in package_ids
        and language in declaration["languageMappings"]
    ]


def _rust_string_literal(value: str) -> str:
    escaped: list[str] = []
    for character in value:
        codepoint = ord(character)
        if character == "\\":
            escaped.append("\\\\")
        elif character == '"':
            escaped.append('\\"')
        elif character == "\n":
            escaped.append("\\n")
        elif character == "\r":
            escaped.append("\\r")
        elif character == "\t":
            escaped.append("\\t")
        elif codepoint < 0x20 or codepoint == 0x7F:
            escaped.append(f"\\u{{{codepoint:x}}}")
        else:
            escaped.append(character)
    return '"' + "".join(escaped) + '"'


def render_public_rust_api(projection: dict[str, Any]) -> str:
    rust_declarations = _language_declarations(projection, "rust")
    c_capabilities = sorted(
        capability["capabilityId"]
        for capability in projection["capabilities"]
        if capability["capabilityState"] in {"declared", "verified"}
        and capability.get("mappings", {}).get("c")
    )
    c_capability_literals = [_rust_string_literal(capability) for capability in c_capabilities]
    lines = [
        "// @generated by tools/api_manifest/generate.py; do not edit.",
        "// Mechanical API inventory only; reviewed FFI code owns behavior.",
        "pub(crate) const PUBLIC_API_FORMAT_VERSION: u32 = 2;",
    ]
    capabilities_inline = (
        "pub(crate) const C_AVAILABLE_CAPABILITIES: &[&str] = &["
        + ", ".join(c_capability_literals)
        + "];"
    )
    if len(capabilities_inline) <= 100:
        lines.append(capabilities_inline)
    else:
        lines.extend([
            "pub(crate) const C_AVAILABLE_CAPABILITIES: &[&str] = &[",
            *(f"    {literal}," for literal in c_capability_literals),
            "];",
        ])
    lines.append("pub(crate) const PUBLIC_API_DECLARATIONS: &[(&str, &str, &str)] = &[")
    for declaration in rust_declarations:
        literals = [
            _rust_string_literal(declaration[field])
            for field in ("declarationId", "packageId", "name")
        ]
        inline = "    (" + ", ".join(literals) + "),"
        if len(inline) <= 72:
            lines.append(inline)
        else:
            lines.extend(["    (", *(f"        {literal}," for literal in literals), "    ),"])
    lines.extend(["];"])
    return "\n".join(lines) + "\n"


def render_public_java_api(projection: dict[str, Any]) -> str:
    declarations = _dump_json(_language_declarations(projection, "java"))
    # Keep each Java constant-pool UTF-8 entry below the class-file limit.
    # Eight thousand Unicode code points remain below 48 KiB even when every
    # code point is encoded as a surrogate pair in modified UTF-8.
    chunk_size = 8_000
    chunks = [
        declarations[offset:offset + chunk_size]
        for offset in range(0, len(declarations), chunk_size)
    ] or [""]
    lines = [
        "// @generated by tools/api_manifest/generate.py; do not edit.",
        "package org.kmipkit.generated;",
        "",
        "/** Generated metadata for the approved public Java declarations. */",
        "public final class PublicApi {",
        "    public static final int FORMAT_VERSION = 2;",
        "    private static final String[] DECLARATIONS_JSON_PARTS = {",
        *(f"        {_java_string_literal(chunk)}," for chunk in chunks),
        "    };",
        '    public static final String DECLARATIONS_JSON = String.join("", DECLARATIONS_JSON_PARTS);',
        "    private PublicApi() {}",
        "}",
        "",
    ]
    return "\n".join(lines)


def _java_string_literal(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return '"' + escaped + '"'


