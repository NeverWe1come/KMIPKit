class ManifestError(ValueError):
    """The manifest is malformed, invalid, or inconsistent with its schema."""


class PathSecurityError(ValueError):
    """An output path is unsafe or differs from the approved destination list."""


def _reject_constant(value: str) -> None:
    raise ManifestError("JSON contains a non-finite number")


def _parse_float(value: str) -> float:
    parsed = float(value)
    if not math.isfinite(parsed):
        raise ManifestError("JSON contains a non-finite number")
    return parsed


def _unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ManifestError("JSON contains a duplicate object member")
        result[key] = value
    return result


def _dump_json(value: Any, *, indent: int | None = None) -> str:
    options: dict[str, Any] = {"ensure_ascii": False, "sort_keys": True}
    if indent is None:
        options["separators"] = (",", ":")
    else:
        options["indent"] = indent
    return json.dumps(value, **options)


def _load_json(root: Path, relative_path: str, max_bytes: int) -> Any:
    path = root / relative_path
    data = path.read_bytes()
    if len(data) > max_bytes:
        raise ManifestError("manifest input exceeds the supported file size")
    try:
        return json.loads(
            data.decode("utf-8"),
            object_pairs_hook=_unique_object,
            parse_constant=_reject_constant,
            parse_float=_parse_float,
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ManifestError("manifest input is not valid UTF-8 JSON") from error


def _json_type_matches(value: Any, expected: str) -> bool:
    if expected == "object":
        return isinstance(value, dict)
    if expected == "array":
        return isinstance(value, list)
    if expected == "string":
        return isinstance(value, str)
    if expected == "boolean":
        return isinstance(value, bool)
    if expected == "integer":
        return isinstance(value, int) and not isinstance(value, bool)
    if expected == "number":
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    if expected == "null":
        return value is None
    return False


def _json_equal(left: Any, right: Any) -> bool:
    if isinstance(left, bool) or isinstance(right, bool):
        return type(left) is type(right) and left == right
    if isinstance(left, (int, float)) and isinstance(right, (int, float)):
        return left == right
    if isinstance(left, dict) and isinstance(right, dict):
        return left.keys() == right.keys() and all(_json_equal(left[key], right[key]) for key in left)
    if isinstance(left, list) and isinstance(right, list):
        return len(left) == len(right) and all(_json_equal(a, b) for a, b in zip(left, right))
    return type(left) is type(right) and left == right


def _json_hashable(value: Any) -> Any:
    if isinstance(value, bool):
        return ("boolean", value)
    if value is None:
        return ("null",)
    if isinstance(value, (int, float)):
        return ("number", Decimal(str(value)).normalize())
    if isinstance(value, str):
        return ("string", value)
    if isinstance(value, list):
        return ("array", tuple(_json_hashable(item) for item in value))
    if isinstance(value, dict):
        return ("object", tuple(sorted((key, _json_hashable(item)) for key, item in value.items())))
    raise ManifestError("JSON contains an unsupported value")


def _resolve_pointer(document: Any, reference: str) -> Any:
    if not reference.startswith("#/"):
        raise ManifestError("schema uses an unsupported external reference")
    current = document
    for part in reference[2:].split("/"):
        key = part.replace("~1", "/").replace("~0", "~")
        try:
            current = current[int(key)] if isinstance(current, list) else current[key]
        except (KeyError, IndexError, ValueError, TypeError) as error:
            raise ManifestError("schema contains an unresolved local reference") from error
    return current


def _schema_matches(
    value: Any,
    schema: Any,
    root_schema: dict[str, Any],
    path: str,
    errors: list[str],
) -> bool:
    """Validate the core Draft 2020-12 vocabulary used by the checked-in schema."""
    initial_error_count = len(errors)
    if schema is True:
        return True
    if schema is False:
        errors.append(path or "manifest")
        return False
    if not isinstance(schema, dict):
        errors.append(path or "manifest")
        return False

    if "$ref" in schema:
        referenced = _resolve_pointer(root_schema, schema["$ref"])
        _schema_matches(value, referenced, root_schema, path, errors)

    if "type" in schema:
        allowed_types = schema["type"] if isinstance(schema["type"], list) else [schema["type"]]
        if not any(_json_type_matches(value, item) for item in allowed_types):
            errors.append(path or "manifest")
            return False

    if "const" in schema and not _json_equal(value, schema["const"]):
        errors.append(path or "manifest")
    if "enum" in schema and not any(_json_equal(value, choice) for choice in schema["enum"]):
        errors.append(path or "manifest")

    for keyword in ("allOf", "anyOf", "oneOf"):
        if keyword not in schema:
            continue
        outcomes: list[bool] = []
        for child in schema[keyword]:
            child_errors: list[str] = []
            outcomes.append(_schema_matches(value, child, root_schema, path, child_errors))
        successes = sum(outcomes)
        valid = successes == len(outcomes) if keyword == "allOf" else (
            successes > 0 if keyword == "anyOf" else successes == 1
        )
        if not valid:
            errors.append(path or "manifest")

    if "not" in schema:
        child_errors: list[str] = []
        if _schema_matches(value, schema["not"], root_schema, path, child_errors):
            errors.append(path or "manifest")

    if "if" in schema:
        condition_errors: list[str] = []
        branch = "then" if _schema_matches(value, schema["if"], root_schema, path, condition_errors) else "else"
        if branch in schema:
            _schema_matches(value, schema[branch], root_schema, path, errors)

    if isinstance(value, dict):
        if "propertyNames" in schema:
            for name in value:
                _schema_matches(
                    name,
                    schema["propertyNames"],
                    root_schema,
                    f"{path}/{name}" if path else name,
                    errors,
                )
        missing = [name for name in schema.get("required", []) if name not in value]
        for name in missing:
            errors.append(f"{path}/{name}" if path else name)
        properties = schema.get("properties", {})
        for name, child_value in value.items():
            child_schema = properties.get(name)
            if child_schema is None:
                additional = schema.get("additionalProperties", True)
                if additional is False:
                    errors.append(f"{path}/{name}" if path else name)
                elif isinstance(additional, (dict, bool)):
                    _schema_matches(
                        child_value,
                        additional,
                        root_schema,
                        f"{path}/{name}" if path else name,
                        errors,
                    )
                continue
            _schema_matches(
                child_value,
                child_schema,
                root_schema,
                f"{path}/{name}" if path else name,
                errors,
            )

    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            errors.append(path or "manifest")
        if len(value) > schema.get("maxItems", len(value)):
            errors.append(path or "manifest")
        for index, child_schema in enumerate(schema.get("prefixItems", [])):
            if index < len(value):
                _schema_matches(value[index], child_schema, root_schema, f"{path}/{index}", errors)
        if "items" in schema:
            start = len(schema.get("prefixItems", []))
            for index in range(start, len(value)):
                _schema_matches(value[index], schema["items"], root_schema, f"{path}/{index}", errors)
        if schema.get("uniqueItems"):
            normalized = [_json_hashable(item) for item in value]
            if len(set(normalized)) != len(normalized):
                errors.append(path or "manifest")

    if isinstance(value, str):
        if len(value) < schema.get("minLength", 0):
            errors.append(path or "manifest")
        if "pattern" in schema and re.search(schema["pattern"], value) is None:
            errors.append(path or "manifest")

    if isinstance(value, (int, float)) and not isinstance(value, bool):
        if "minimum" in schema and value < schema["minimum"]:
            errors.append(path or "manifest")
        if "maximum" in schema and value > schema["maximum"]:
            errors.append(path or "manifest")

    return len(errors) == initial_error_count


def _check_schema_subset(schema: dict[str, Any]) -> None:
    supported = {
        "$defs", "$id", "$schema", "additionalProperties", "allOf", "anyOf", "const",
        "description", "else", "enum", "format", "if", "items", "maximum", "minItems",
        "minLength", "minimum", "not", "oneOf", "pattern", "prefixItems", "properties",
        "propertyNames",
        "required", "then", "title", "type", "uniqueItems", "$ref", "maxItems",
    }
    def visit(schema_node: Any) -> None:
        if isinstance(schema_node, bool):
            return
        if isinstance(schema_node, dict):
            unsupported = set(schema_node) - supported
            if unsupported:
                raise ManifestError("schema contains unsupported validation keywords")
            for name in ("$defs", "properties"):
                for child in schema_node.get(name, {}).values():
                    visit(child)
            for name in ("items", "additionalProperties", "propertyNames", "not", "if", "then", "else"):
                child = schema_node.get(name)
                if isinstance(child, (dict, bool)):
                    visit(child)
            for name in ("allOf", "anyOf", "oneOf", "prefixItems"):
                for child in schema_node.get(name, []):
                    visit(child)
    visit(schema)


def _validate_schema(manifest: Any, schema: dict[str, Any]) -> None:
    _check_schema_subset(schema)
    errors: list[str] = []
    _schema_matches(manifest, schema, schema, "", errors)
    if errors:
        location = errors[0].replace("~", "~0").replace("/", "~1")
        raise ManifestError(f"manifest does not match the declared schema near {location}")


def _operation_section(source_refs: list[Any]) -> tuple[str, tuple[int, ...]]:
    sections = [
        reference.get("section")
        for reference in source_refs
        if isinstance(reference, dict) and reference.get("source_id") == "KMIPKIT-SRC-spec"
    ]
    if len(sections) != 1 or not isinstance(sections[0], str):
        raise ManifestError("client operation does not resolve to one KMIP 2.1 section")
    section = sections[0]
    match = re.fullmatch(r"6\.1\.([0-9]+)", section)
    if match is None:
        raise ManifestError("client operation has an invalid KMIP 2.1 section")
    return section, (6, 1, int(match.group(1)))


def _validate_operation_inventory(manifest: dict[str, Any], catalog: dict[str, Any]) -> None:
    """Require an exact, numerically ordered copy of the client 1.0 catalog operations."""
    catalog_elements = catalog.get("elements")
    if not isinstance(catalog_elements, list):
        raise ManifestError("normative catalog does not contain an element inventory")

    expected: list[tuple[tuple[int, ...], dict[str, str]]] = []
    seen_catalog_ids: set[str] = set()
    for element in catalog_elements:
        if not isinstance(element, dict):
            raise ManifestError("normative catalog contains a malformed element")
        if element.get("kind") != "operation" or element.get("scope_state") != "client_1_0":
            continue

        operation_id = element.get("element_id")
        name = element.get("name")
        source_refs = element.get("source_refs")
        if not isinstance(operation_id, str) or not isinstance(name, str) or not isinstance(source_refs, list):
            raise ManifestError("normative catalog contains a malformed client operation")
        if operation_id in seen_catalog_ids:
            raise ManifestError("normative catalog contains duplicate client operation IDs")
        seen_catalog_ids.add(operation_id)

        section, section_order = _operation_section(source_refs)
        expected.append(
            (
                section_order,
                {
                    "operationId": operation_id,
                    "name": name,
                    "section": section,
                    "scope": "client_1_0",
                },
            )
        )

    if len(expected) != 57:
        raise ManifestError("normative catalog must contain exactly 57 client 1.0 operations")
    expected.sort(key=lambda item: item[0])

    rows = manifest.get("operations")
    if not isinstance(rows, list) or len(rows) != len(expected):
        raise ManifestError("manifest operation inventory must contain exactly 57 rows")
    operation_ids = [row.get("operationId") for row in rows if isinstance(row, dict)]
    if len(operation_ids) != len(rows) or len(set(operation_ids)) != len(rows):
        raise ManifestError("manifest operation inventory contains malformed or duplicate IDs")

    expected_rows = [row for _, row in expected]
    expected_ids = [row["operationId"] for row in expected_rows]
    if set(operation_ids) != set(expected_ids):
        raise ManifestError("manifest operation inventory differs from the normative catalog")
    if operation_ids != expected_ids:
        raise ManifestError("manifest operations are not ordered by numeric KMIP section")
    for actual, wanted in zip(rows, expected_rows):
        if any(actual.get(field) != value for field, value in wanted.items()):
            raise ManifestError("manifest operation name, section, or scope differs from the catalog")


def _manifest_file(root: Path, relative_path: Any) -> tuple[Path, str]:
    if not isinstance(relative_path, str) or "\\" in relative_path:
        raise ManifestError("manifest evidence path is invalid")
    posix_path = PurePosixPath(relative_path)
    if posix_path.is_absolute() or any(part in {"", ".", ".."} for part in posix_path.parts):
        raise ManifestError("manifest evidence path is invalid")
    checkout = root.resolve(strict=True)
    candidate = checkout.joinpath(*posix_path.parts)
    try:
        resolved = candidate.resolve(strict=True)
        resolved.relative_to(checkout)
    except (OSError, ValueError) as error:
        raise ManifestError("manifest evidence does not resolve inside the repository") from error
    if not resolved.is_file():
        raise ManifestError("manifest evidence does not resolve to a repository file")
    try:
        content = resolved.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise ManifestError("manifest evidence is not readable UTF-8 text") from error
    return resolved, content


def _feature_directory(root: Path, feature_id: Any) -> Path:
    if not isinstance(feature_id, str) or re.fullmatch(r"KMIPKIT-[0-9]{4}", feature_id) is None:
        raise ManifestError("manifest feature owner ID is invalid")
    number = int(feature_id[-4:])
    prefix = f"{number:03d}-"
    matches = sorted((root / "specs").glob(f"{prefix}*"))
    if len(matches) != 1 or not matches[0].is_dir():
        raise ManifestError("manifest feature owner does not resolve to one specification")
    return matches[0]


def _status_from_document(content: str) -> str:
    match = re.search(r"(?m)^\*\*Status\*\*:\s*(Approved|Accepted)\b", content)
    if match is None:
        raise ManifestError("manifest owner source is not approved or accepted")
    return match.group(1)


def _validate_approval_source(
    source: Any,
    root: Path,
    *,
    feature_id: Any = None,
    adr_id: Any = None,
) -> None:
    if not isinstance(source, dict):
        raise ManifestError("ready manifest record has no approval evidence")
    kind = source.get("kind")
    relative_path = source.get("path")
    recorded_status = source.get("status")
    evidence = source.get("evidence")
    _, evidence_content = _manifest_file(root, relative_path)
    if not isinstance(evidence, str) or not evidence or evidence not in evidence_content:
        raise ManifestError("manifest approval evidence does not match its cited file")

    if kind == "feature-specification":
        if adr_id is not None:
            raise ManifestError("feature approval evidence cannot satisfy an ADR owner")
        parts = PurePosixPath(relative_path).parts
        if len(parts) < 3 or parts[0] != "specs":
            raise ManifestError("feature approval evidence is outside its specification")
        if feature_id is not None:
            owner = _feature_directory(root, feature_id)
            if parts[1] != owner.name:
                raise ManifestError("feature approval evidence refers to a different owner")
        spec_path = root / "specs" / parts[1] / "spec.md"
        _, spec_content = _manifest_file(root, PurePosixPath(*spec_path.relative_to(root).parts).as_posix())
        actual_status = _status_from_document(spec_content)
        if recorded_status != actual_status:
            raise ManifestError("manifest feature approval status differs from its specification")
        return

    if kind == "accepted-adr":
        if feature_id is not None:
            raise ManifestError("ADR acceptance evidence cannot satisfy a feature owner")
        parts = PurePosixPath(relative_path).parts
        if len(parts) != 3 or parts[:2] != ("docs", "adr"):
            raise ManifestError("ADR evidence is outside the accepted ADR directory")
        if adr_id is not None:
            if not isinstance(adr_id, str) or re.fullmatch(r"ADR-[0-9]{4}", adr_id) is None:
                raise ManifestError("manifest ADR owner ID is invalid")
            if not parts[2].startswith(f"{adr_id[-4:]}-"):
                raise ManifestError("ADR evidence refers to a different owner")
        actual_status = _status_from_document(evidence_content)
        if actual_status != "Accepted" or recorded_status != "Accepted":
            raise ManifestError("ADR owner is not accepted")
        return

    raise ManifestError("manifest approval evidence has an unsupported source kind")


def _validate_parity_evidence(record: dict[str, Any], root: Path) -> None:
    evidence_ids = record.get("parityEvidenceIds", [])
    if not isinstance(evidence_ids, list):
        raise ManifestError("manifest parity evidence list is malformed")
    for evidence_id in evidence_ids:
        _manifest_file(root, evidence_id)


def _validate_operation_readiness(
    operations: list[dict[str, Any]],
    declarations_by_id: dict[str, dict[str, Any]],
    root: Path,
) -> None:
    for operation in operations:
        if not isinstance(operation, dict):
            raise ManifestError("manifest operation readiness record is malformed")
        state = operation.get("apiState")
        if state in {"declared", "verified"}:
            if operation.get("candidateSpecId") is not None:
                raise ManifestError("ready operation still records a candidate owner")
            _validate_approval_source(
                operation.get("approvalEvidence"),
                root,
                feature_id=operation.get("featureSpecId"),
            )
            declarations_by_language = operation.get("declarations", {})
            for language in ("rust", "c", "java", "python"):
                for declaration_id in declarations_by_language.get(language, []):
                    declaration = declarations_by_id.get(declaration_id)
                    if declaration is None:
                        raise ManifestError("operation mapping references an unknown declaration")
                    if language not in declaration.get("languageMappings", {}):
                        raise ManifestError("operation declaration lacks its language mapping")
                    if declaration.get("declarationState") == "blocked":
                        raise ManifestError("ready operation maps to a blocked public declaration")
        if state == "verified":
            _validate_parity_evidence(operation, root)


def _validate_capability_readiness(
    capabilities: list[dict[str, Any]], root: Path
) -> None:
    for capability in capabilities:
        if not isinstance(capability, dict):
            raise ManifestError("manifest capability readiness record is malformed")
        state = capability.get("capabilityState")
        if state in {"declared", "verified"}:
            if capability.get("ownerSpecId") is not None:
                _validate_approval_source(
                    capability.get("approvalEvidence"),
                    root,
                    feature_id=capability.get("ownerSpecId"),
                )
            else:
                _validate_approval_source(
                    capability.get("acceptedEvidence"),
                    root,
                    adr_id=capability.get("ownerAdrId"),
                )
        if state == "verified":
            _validate_parity_evidence(capability, root)


def _validate_public_declarations(
    declarations: list[dict[str, Any]],
    capabilities_by_id: dict[Any, dict[str, Any]],
    operations_by_id: dict[Any, dict[str, Any]],
    package_languages: dict[Any, Any],
    requirements: set[Any],
    root: Path,
) -> None:
    for declaration in declarations:
        if not isinstance(declaration, dict):
            raise ManifestError("manifest public declaration is malformed")
        capability_id = declaration.get("capabilityId")
        capability = capabilities_by_id.get(capability_id)
        operation = operations_by_id.get(capability_id)
        if capability is None and operation is None:
            raise ManifestError("public declaration references an unknown capability")
        package_id = declaration.get("packageId")
        if package_id not in package_languages:
            raise ManifestError("public declaration references an unknown package")
        if not set(declaration.get("requirementIds", [])) <= requirements:
            raise ManifestError("public declaration references an unknown requirement")
        parity_scope = _validate_declaration_parity_scope(
            declaration,
            capability_id,
            capability,
            package_id,
            package_languages,
        )
        if declaration.get("declarationState") in {"declared", "verified"}:
            _validate_public_declaration_approval(
                declaration, capability, operation, parity_scope, root
            )
            mappings = declaration.get("languageMappings", {})
            required_languages = ("rust",) if parity_scope == "rust-only-adr" else (
                "rust", "c", "java", "python"
            )
            for language in required_languages:
                mapping = mappings.get(language)
                if not isinstance(mapping, dict):
                    raise ManifestError("public declaration is missing a language mapping")
                package_id = mapping.get("packageId")
                if package_languages.get(package_id) != language:
                    raise ManifestError("public declaration maps to a package in another language")
                if not isinstance(mapping.get("name"), str) or not mapping["name"]:
                    raise ManifestError("public declaration mapping has no exported name")
            owning_language = package_languages[declaration["packageId"]]
            if mappings.get(owning_language, {}).get("packageId") != declaration["packageId"]:
                raise ManifestError("declaration package differs from its owning language mapping")
        if declaration.get("declarationState") == "verified":
            _validate_parity_evidence(declaration, root)


def _validate_declaration_parity_scope(
    declaration: dict[str, Any],
    capability_id: Any,
    capability: dict[str, Any] | None,
    package_id: Any,
    package_languages: dict[Any, Any],
) -> Any:
    parity_scope = declaration.get("parityScope")
    if capability is not None and parity_scope != capability.get("parityScope"):
        raise ManifestError("public declaration parity scope differs from its capability")
    if parity_scope == "rust-only-adr":
        accepted_transport_exception = (
            package_id == "rust-kmipkit-transport"
            and package_languages.get(package_id) == "rust"
            and capability_id == "rust_transport_exchange"
            and capability is not None
            and capability.get("ownerAdrId") == "ADR-0014"
            and capability.get("capabilityState") in {"declared", "verified"}
            and declaration.get("approvalSource") == capability.get("acceptedEvidence")
        )
        if not accepted_transport_exception:
            raise ManifestError("Rust-only parity is reserved for accepted ADR-0014 transport declarations")
    elif parity_scope != "four-language":
        raise ManifestError("public declaration has an unsupported parity scope")
    return parity_scope


def _validate_public_declaration_approval(
    declaration: dict[str, Any],
    capability: dict[str, Any] | None,
    operation: dict[str, Any] | None,
    parity_scope: Any,
    root: Path,
) -> None:
    if capability is not None:
        owner_spec_id = capability.get("ownerSpecId") or capability.get("candidateSpecId")
        owner_adr_id = capability.get("ownerAdrId")
    else:
        if operation is None or operation.get("apiState") not in {"declared", "verified"}:
            raise ManifestError("ready public declaration references a blocked operation")
        owner_spec_id = operation.get("featureSpecId")
        owner_adr_id = None

    if owner_adr_id is not None:
        if parity_scope != "rust-only-adr":
            raise ManifestError("ADR-owned public declaration is not scoped to its accepted Rust-only capability")
        _validate_approval_source(
            declaration.get("approvalSource"), root, adr_id=owner_adr_id
        )
    else:
        if parity_scope != "four-language":
            raise ManifestError("feature-owned public declaration has an invalid parity scope")
        _validate_approval_source(
            declaration.get("approvalSource"), root, feature_id=owner_spec_id
        )


def _validate_approved_exclusions(
    exclusions: list[dict[str, Any]], package_languages: dict[Any, Any], root: Path
) -> None:
    for exclusion in exclusions:
        if not isinstance(exclusion, dict):
            raise ManifestError("manifest approved exclusion is malformed")
        _validate_approval_source(exclusion.get("approvalSource"), root)


def _require_complete_readiness(
    operations: list[dict[str, Any]],
    capabilities: list[dict[str, Any]],
    declarations: list[dict[str, Any]],
) -> None:
    if len(operations) != 57 or any(
        record.get("apiState") != "verified" for record in operations
    ):
        raise ManifestError("release manifest contains an incomplete operation API")
    if any(record.get("capabilityState") != "verified" for record in capabilities):
        raise ManifestError("release manifest contains an incomplete capability API")
    if any(record.get("declarationState") != "verified" for record in declarations):
        raise ManifestError("release manifest contains an incomplete public declaration")


def _validate_v2_readiness(
    manifest: dict[str, Any],
    root: Path,
    *,
    require_complete: bool = False,
) -> None:
    """Resolve v2 readiness claims to approved sources, packages, and evidence."""
    operations = manifest.get("operations", [])
    capabilities = manifest.get("capabilities", [])
    declarations = manifest.get("publicDeclarations", [])
    exclusions = manifest.get("approvedExclusions", [])
    packages = manifest.get("publicPackages", [])
    requirements = set(manifest.get("requirementIds", []))
    package_languages = {
        package.get("id"): package.get("language")
        for package in packages
        if isinstance(package, dict)
    }
    capabilities_by_id = {
        record.get("capabilityId"): record
        for record in capabilities
        if isinstance(record, dict)
    }
    operations_by_id = {
        record.get("operationId"): record
        for record in operations
        if isinstance(record, dict)
    }
    declaration_by_id = {
        record.get("declarationId"): record
        for record in declarations
        if isinstance(record, dict)
    }
    if len(declaration_by_id) != len(declarations):
        raise ManifestError("manifest public declaration IDs are malformed or duplicated")

    if require_complete:
        _require_complete_readiness(operations, capabilities, declarations)
    _validate_operation_readiness(operations, declaration_by_id, root)
    _validate_capability_readiness(capabilities, root)
    _validate_public_declarations(
        declarations,
        capabilities_by_id,
        operations_by_id,
        package_languages,
        requirements,
        root,
    )
    _validate_approved_exclusions(exclusions, package_languages, root)
    if require_complete and not package_languages:
        raise ManifestError("release manifest contains no public packages")


def _validate_v2_manifest(
    manifest: dict[str, Any],
    schema: dict[str, Any],
    catalog: dict[str, Any],
    root: Path,
    *,
    require_complete: bool = False,
) -> None:
    """Validate v2 schema, normative catalog, references, and readiness together."""
    _validate_schema(manifest, schema)
    _validate_operation_inventory(manifest, catalog)
    _validate_references(manifest)
    _validate_v2_readiness(manifest, root, require_complete=require_complete)


def _require_unique(records: list[dict[str, Any]], field: str, label: str) -> set[Any]:
    values = [record[field] for record in records]
    if len(set(values)) != len(values):
        raise ManifestError(f"manifest contains duplicate {label}")
    return set(values)


def _validate_references(manifest: dict[str, Any]) -> None:
    root_requirements = set(manifest["requirementIds"])
    error_ids = _require_unique(manifest["errorCategories"], "id", "error category IDs")
    _require_unique(manifest["types"], "id", "type IDs")
    _require_unique(manifest["functions"], "id", "function IDs")
    _require_unique(manifest["errorCategories"], "cValue", "C error values")
    _require_unique(manifest["errorCategories"], "cCode", "C error codes")
    c_symbols = [function["c"]["symbol"] for function in manifest["functions"]]
    release_symbols = [
        record["c"]["releaseFunction"]
        for record in manifest["types"]
        if record["c"]["kind"] == "opaque-handle"
    ]
    all_symbols = [*c_symbols, *release_symbols]
    if len(set(c_symbols)) != len(c_symbols) or len(set(all_symbols)) != len(all_symbols):
        raise ManifestError("manifest contains duplicate C function symbols")

    for record in [*manifest["types"], *manifest["functions"]]:
        if any(identifier not in root_requirements for identifier in record["requirementIds"]):
            raise ManifestError("declaration references an unknown requirement ID")
    requirement_lists = [
        manifest["requirementIds"],
        *(record["requirementIds"] for record in [*manifest["types"], *manifest["functions"]]),
    ]
    if any(identifiers != sorted(set(identifiers)) for identifiers in requirement_lists):
        raise ManifestError("requirement IDs must be unique and lexicographically sorted")
    for limit in manifest["limits"]:
        if limit["errorCategory"] not in error_ids:
            raise ManifestError("limit references an unknown error category")

    c_handle_names = {
        record["c"]["name"]: record
        for record in manifest["types"]
        if record["c"]["kind"] == "opaque-handle"
    }
    for record in manifest["functions"]:
        for language in ("c", "java", "python"):
            function_errors = set(record[language]["errorCategories"])
            if not function_errors <= error_ids:
                raise ManifestError("function references an unknown error category")
        params = record["c"]["parameters"]
        parameter_names = [parameter["name"] for parameter in params]
        if len(set(parameter_names)) != len(parameter_names):
            raise ManifestError("C function parameter names must be unique")
        param_by_name = {param["name"]: param for param in params}
        for param in params:
            if param["kind"] == "byte-span":
                length = param_by_name.get(param["byteLengthParameter"])
                if length is None or length["kind"] != "scalar" or length["type"] != param["byteLengthType"]:
                    raise ManifestError("byte-span length must name a matching scalar parameter")
            elif param["kind"] == "handle":
                handle_name = param["type"].split()[0].rstrip("*").strip()
                if handle_name not in c_handle_names:
                    raise ManifestError("function handle parameter references an unknown opaque type")
            elif param["kind"] == "handle-array":
                handle_name = param["handleType"]
                if handle_name not in c_handle_names:
                    raise ManifestError("function handle array references an unknown opaque type")
                if param["type"] != f"{handle_name} **":
                    raise ManifestError("function handle array pointer type does not match its opaque type")
                count = param_by_name.get(param["countParameter"])
                if count is None or count["kind"] != "scalar" or count["type"] != "uint64_t":
                    raise ManifestError("function handle array count must name a uint64_t scalar parameter")
            elif param["kind"] == "output" and "**" in param["type"]:
                handle_name = param["type"].split()[0].strip()
                if handle_name not in c_handle_names:
                    raise ManifestError("function output references an unknown opaque type")
        if any(parameter["kind"] in {"handle", "handle-array"} for parameter in params):
            if any(
                "invalid_input" not in record[language]["errorCategories"]
                for language in ("c", "java", "python")
            ):
                raise ManifestError("handle-taking functions must map invalid_input in every adapter")
        if record["id"] in {"ttlv_value_enumeration", "ttlv_value_interval"}:
            if any(
                "invalid_input" not in record[language]["errorCategories"]
                for language in ("java", "python")
            ):
                raise ManifestError("Java and Python Enumeration/Interval constructors must map invalid_input")
        if record["id"] == "ttlv_value_boolean" and "invalid_input" not in record["c"]["errorCategories"]:
            raise ManifestError("C Boolean construction must map invalid_input")

    for record in manifest["types"]:
        if record["kind"] != "enum":
            continue
        values = record["enumRepresentation"]["values"]
        names = [entry["name"] for entry in values]
        numbers = [entry["value"] for entry in values]
        if len(set(names)) != len(names) or len(set(numbers)) != len(numbers):
            raise ManifestError("enum names and numeric values must be unique")
        storage = record["c"]["underlyingType"]
        bits = _C_INTEGER_TYPES[storage][1]
        signed = _C_INTEGER_TYPES[storage][2]
        minimum = -(1 << (bits - 1)) if signed else 0
        maximum = (1 << (bits - 1)) - 1 if signed else (1 << bits) - 1
        if any(number < minimum or number > maximum for number in numbers):
            raise ManifestError("enum value does not fit its C storage type")

    if tuple(limit["id"] for limit in manifest["limits"]) != _FIXED_LIMIT_IDS:
        raise ManifestError("manifest limits do not use the approved FR-012 order")
    generated_outputs = manifest["generatedOutputs"]
    if isinstance(generated_outputs, dict):
        legacy_outputs_match = generated_outputs == OUTPUTS
    else:
        output_paths = {
            record.get("path")
            for record in generated_outputs
            if isinstance(record, dict)
        }
        legacy_outputs_match = set(OUTPUTS.values()) <= output_paths
    if not legacy_outputs_match:
        raise PathSecurityError("manifest output paths differ from the approved six destinations")


def _c_parameter_type(parameter: dict[str, Any]) -> str:
    return parameter["type"]


def _c_declaration(function: dict[str, Any]) -> str:
    parameters = function["c"]["parameters"]
    arguments = ", ".join(f"{_c_parameter_type(item)} {item['name']}" for item in parameters) or "void"
    return f"{function['c']['returnType']} {function['c']['symbol']}({arguments});"


def _rust_c_type(c_type: str) -> str:
    match = re.fullmatch(r"(const\s+)?([A-Za-z_][A-Za-z0-9_]*)(\s*\*+)?", c_type)
    if match is None:
        raise ManifestError("C signature cannot be represented in the Rust FFI mapping")
    const, base, stars = match.groups()
    rust_base = _C_INTEGER_TYPES.get(base, (base, 0, False))[0]
    pointer_count = stars.count("*") if stars else 0
    if pointer_count == 0:
        return rust_base
    pointer = "*const" if const and pointer_count == 1 else "*mut"
    return " ".join([pointer] * pointer_count + [rust_base])


def _rust_identifier(name: str) -> str:
    if name in _RUST_RAW_IDENTIFIER_FORBIDDEN:
        raise ManifestError("C parameter name cannot be represented as a Rust FFI identifier")
    return f"r#{name}" if name in _RUST_2024_KEYWORDS else name


def render_rust_ffi(manifest: dict[str, Any]) -> str:
    lines = [
        "// @generated by tools/api_manifest/generate.py; do not edit.",
        "#![allow(non_camel_case_types, non_snake_case)]",
        "",
        "pub const PUBLIC_API_MANIFEST_FORMAT_VERSION: u32 = 1;",
    ]
    emitted: set[str] = set()
    for declaration in manifest["types"]:
        c_type = declaration["c"]
        name = c_type["name"]
        if name in emitted:
            continue
        emitted.add(name)
        if c_type["kind"] == "opaque-handle":
            lines.extend(["#[repr(C)]", f"pub struct {name} {{ _private: [u8; 0] }}"])
        elif c_type["kind"] == "enum":
            storage = _C_INTEGER_TYPES[c_type["underlyingType"]][0]
            lines.append(f"pub type {name} = {storage};")
            for value in declaration["enumRepresentation"]["values"]:
                const_name = f"{name[:-2].upper()}_{re.sub(r'(?<!^)(?=[A-Z])', '_', value['name']).upper()}"
                lines.append(f"pub const {const_name}: {name} = {value['value']};")
        elif c_type["kind"] == "fixed-width-value":
            lines.extend(["#[repr(C)]", f"pub struct {name} {{"])
            for limit in manifest["limits"]:
                lines.append(f"    pub {limit['cField']}: u64,")
            lines.append("}")
        lines.append("")
    lines.extend(["unsafe extern \"C\" {"])
    for declaration in manifest["types"]:
        c_type = declaration["c"]
        if c_type["kind"] == "opaque-handle":
            lines.append(f"    pub fn {c_type['releaseFunction']}(handle: *mut {c_type['name']});")
    for function in manifest["functions"]:
        lines.append(f"    // {', '.join(function['requirementIds'])}")
        parameters = function["c"]["parameters"]
        args = ", ".join(
            f"{_rust_identifier(parameter['name'])}: {_rust_c_type(parameter['type'])}"
            for parameter in parameters
        )
        result = _rust_c_type(function["c"]["returnType"])
        lines.append(f"    pub fn {function['c']['symbol']}({args}) -> {result};")
    lines.extend(["}", ""])
    return "\n".join(lines)


def render_c_header(manifest: dict[str, Any]) -> str:
    lines = [
        "/* @generated by tools/api_manifest/generate.py; do not edit. */",
        "#ifndef KMIPKIT_H",
        "#define KMIPKIT_H",
        "#include <stdint.h>",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
    ]
    emitted: set[str] = set()
    for declaration in manifest["types"]:
        c_type = declaration["c"]
        name = c_type["name"]
        if name in emitted:
            continue
        emitted.add(name)
        if c_type["kind"] == "opaque-handle":
            lines.append(f"typedef struct {name} {name};")
        elif c_type["kind"] == "enum":
            lines.append(f"typedef {c_type['underlyingType']} {name};")
            prefix = name[:-2].upper()
            for value in declaration["enumRepresentation"]["values"]:
                const_name = f"{prefix}_{re.sub(r'(?<!^)(?=[A-Z])', '_', value['name']).upper()}"
                lines.append(f"#define {const_name} (({name}){value['value']})")
        elif c_type["kind"] == "fixed-width-value":
            lines.append("typedef struct {")
            for limit in manifest["limits"]:
                lines.append(f"    uint64_t {limit['cField']};")
            lines.append(f"}} {name};")
        lines.append("")
    for declaration in manifest["types"]:
        c_type = declaration["c"]
        if c_type["kind"] == "opaque-handle":
            lines.append(f"void {c_type['releaseFunction']}({c_type['name']} *handle);")
    for error in manifest["errorCategories"]:
        lines.append(f"#define {error['cCode']} ((int32_t){error['cValue']})")
    lines.append("")
    for function in manifest["functions"]:
        requirement_comment = ", ".join(function["requirementIds"])
        if any(
            parameter["kind"] == "handle-array" and parameter["nullable"]
            for parameter in function["c"]["parameters"]
        ):
            lines.extend([
                "/* For nullable handle arrays, NULL is valid only when the linked count is zero.",
                " * Implementations must check the count before reading elements and return",
                " * invalid_input when a NULL array has a nonzero count. */",
            ])
        lines.append(f"/* {requirement_comment} */")
        lines.append(_c_declaration(function))
    lines.extend(["", "#ifdef __cplusplus", "}", "#endif", "#endif /* KMIPKIT_H */", ""])
    return "\n".join(lines)


def _json_literal(value: Any) -> str:
    return _dump_json(value)


def _encode_generated_text(value: str) -> bytes:
    """Encode renderer text with repository-independent UTF-8/LF bytes."""
    return value.replace("\r\n", "\n").replace("\r", "\n").encode("utf-8")


